"""Capital-markets events as structured facts: what instrument, which way the money moves, and how far along it is.

The challenge's category stays "Fund raise", but the label alone conflates opposite events: issuing commercial paper
raises money, redeeming it at maturity pays money back. Treating a redemption as a "raise" produced dilution and
use-of-proceeds language for a routine debt repayment (Titan, Nov 2026). Every field here is read from the filing text
by rules, and each carries the passage that supports it, so a card can say exactly why it reads the event the way it
does. Nothing here is generated by a model.
"""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field

# Instrument, its family (equity dilutes; debt adds leverage), in priority order: the most specific first.
INSTRUMENTS: list[tuple[str, str, str]] = [
    ("commercial_paper", "debt", r"commercial papers?|\bcps?\b(?=[^a-z]{0,20}(?:of|bearing|isin|issued|worth|aggregating))"),
    ("ncd", "debt", r"non[- ]convertible debentures?|\bncds?\b"),
    ("bonds", "debt", r"\bbonds?\b"),
    ("term_loan", "debt", r"term loans?|external commercial borrowing|\becb\b"),
    ("warrants", "equity", r"\bwarrants?\b"),
    ("qip", "equity", r"qualified institutions?\s+placement|\bqip\b"),
    ("rights_issue", "equity", r"rights issue|rights entitlement"),
    ("preferential_issue", "equity", r"preferential (?:issue|allotment|basis)"),
    ("equity_shares", "equity", r"equity shares"),
    ("debentures", "debt", r"debentures?"),
]
INSTRUMENT_LABEL = {
    "commercial_paper": "commercial paper", "ncd": "non-convertible debentures", "bonds": "bonds", "term_loan": "term loan",
    "warrants": "warrants", "qip": "QIP", "rights_issue": "rights issue", "preferential_issue": "preferential issue",
    "equity_shares": "equity shares", "debentures": "debentures",
}

# action -> (pattern, capital direction from the company's point of view)
ACTIONS: list[tuple[str, str, str]] = [
    ("buyback", r"buy-?back", "outflow"),
    ("redemption", r"\bredeem(?:ed|s)?\b|\bredemption\b|maturity proceeds", "outflow"),
    ("repayment", r"\brepa(?:id|y|yment|yments)\b|prepayment|pre-?paid", "outflow"),
    ("issuance", r"\bissu(?:e|ed|ance|ing)\b|\ballot(?:ted|ment)?\b|\braise\b|\braising\b|\bplacement\b|\boffer\b|"
                 r"\bsubscription\b", "inflow"),
]
ACTION_LABEL = {"buyback": "Buyback", "redemption": "Redemption", "repayment": "Repayment", "issuance": "Issuance"}

# Stage, most advanced first. "Approval" is never "completion": a board or shareholder approval only authorises.
STAGES: list[tuple[str, str]] = [
    ("completed", r"(?:has|have) (?:been )?(?:fully |duly )?(?:redeemed|repaid|completed|closed)|"
                  r"(?:duly|have been|has been) (?:paid|credited|completed|listed)|maturity proceeds .{0,60}paid|"
                  r"(?:listing|trading) approval (?:has been |was )?(?:received|granted)|successfully (?:completed|closed)|"
                  r"\bconverted into\b|\bupon conversion\b.{0,40}\ballotted\b|issue (?:has )?closed"),
    ("allotment", r"approved (?:the )?allotment|\ballotted\b|\ballotment of\b"),
    ("opened", r"\b(?:opened|opening|opens)\b.{0,60}\b(?:issue|placement|qip|offer)\b|\bfloor price\b|"
               r"\b(?:issue|placement|qip|offer)\b.{0,30}\b(?:opened|opens)\b"),
    ("regulatory_approval", r"\b(?:rbi|sebi|reserve bank|stock exchanges?|nse|bse)\b.{0,80}\b(?:approval|approved|in-principle)\b|"
                            r"in-principle approval"),
    ("shareholder_approval", r"(?:approval|approved|consent) of (?:the )?(?:members|shareholders)|special resolution|"
                             r"postal ballot|shareholders (?:have )?approved"),
    ("board_approval", r"\b(?:board|committee)\b[^;]{0,160}?\b(?:has |have )?(?:considered and )?approved\b"),
    ("proposed", r"\bto consider\b|\bwill consider\b|\bproposal to\b|\bintends? to\b|\bproposed\b"),
]
STAGE_LABEL = {
    "completed": "Completed", "allotment": "Allotment", "opened": "Issue opened", "regulatory_approval": "Regulatory approval",
    "shareholder_approval": "Shareholder approval", "board_approval": "Board / committee approval", "proposed": "Proposed / notice",
    "unknown": "Disclosure",
}

RUPEES_RE = re.compile(r"(?:₹|rs\.?|inr)\s*(\d{1,3}(?:,\d{2,3}){2,}(?:\.\d+)?)(?!\s*(?:crores?|cr\b|lakhs?|lacs?|billion|bn|million|mn))", re.I)
UNIT_PRICE_RE = re.compile(r"(?:₹|rs\.?|inr)\s*([\d,]+(?:\.\d+)?)\s*(?:\([^)]{0,90}\)\s*)?(?:per|each)\b", re.I)
AMOUNT_RE = re.compile(r"(?:₹|rs\.?|inr)\s*([\d,]+(?:\.\d+)?)\s*(crores?|cr\b|lakhs?|lacs?|billion|bn|million|mn)", re.I)
ISIN_RE = re.compile(r"\bIN[EF][0-9A-Z]{9}\b")
DATE_RE = re.compile(r"\b(\d{1,2})(?:st|nd|rd|th)?\s+(January|February|March|April|May|June|July|August|September|October|"
                     r"November|December)\s*,?\s+(20\d{2})\b|\b(January|February|March|April|May|June|July|August|September|"
                     r"October|November|December)\s+(\d{1,2}),?\s+(20\d{2})\b", re.I)
UNIT_TO_CRORE = {"crore": 1.0, "crores": 1.0, "cr": 1.0, "lakh": 0.01, "lakhs": 0.01, "lac": 0.01, "lacs": 0.01,
                 "billion": 100.0, "bn": 100.0, "million": 0.1, "mn": 0.1}


@dataclass
class FinancialEvent:
    instrument: str | None
    instrument_family: str | None      # equity (dilutive) | debt (leverage)
    action: str                         # issuance | redemption | repayment | buyback | unknown
    capital_direction: str              # inflow (company receives money) | outflow (company pays) | unknown
    stage: str                          # see STAGES, or "unknown"
    amount: float | None = None         # in `unit`
    currency: str = "INR"
    unit: str = "crore"
    amount_text: str | None = None      # as printed in the filing
    unit_price: float | None = None     # ₹ per share/warrant/unit, when stated
    isins: list[str] = field(default_factory=list)
    dates: list[str] = field(default_factory=list)
    evidence: dict[str, str] = field(default_factory=dict)   # field -> verbatim snippet that supports it

    @property
    def subtype(self) -> str:
        inst = INSTRUMENT_LABEL.get(self.instrument or "", "securities")
        if self.action in ("redemption", "repayment"):
            return f"Debt repayment — {inst} {'redeemed' if self.action == 'redemption' else 'repaid'}"
        if self.action == "buyback":
            return "Buyback — cash returned to shareholders"
        if self.action == "issuance":
            kind = "Equity raise" if self.instrument_family == "equity" else "Debt raise" if self.instrument_family == "debt" else "Capital raise"
            return f"{kind} — {inst}"
        return f"Capital-markets disclosure — {inst}"

    def as_dict(self) -> dict:
        d = asdict(self)
        d["subtype"] = self.subtype
        d["stage_label"] = STAGE_LABEL.get(self.stage, "Disclosure")
        d["action_label"] = ACTION_LABEL.get(self.action, "Disclosure")
        return d


def _snippet(text: str, m: re.Match, pad: int = 70) -> str:
    s, e = max(0, m.start() - pad), min(len(text), m.end() + pad)
    return re.sub(r"\s+", " ", text[s:e]).strip()


def _body(text: str) -> str:
    """Drop letterhead boilerplate that mentions regulators/circulars ("In terms of the SEBI Operational Circular …
    regarding issue and listing of …") — it describes the rulebook, not this event."""
    t = re.sub(r"\s+", " ", text or "")
    t = re.sub(r"in terms of (?:the )?(?:sebi|regulation)[^.]{0,260}?(?:commercial paper|securities|regulations?,? \d{4})", " ", t, flags=re.I)
    t = re.sub(r"regarding issue and listing of[^.]{0,200}", " ", t, flags=re.I)
    return t


def parse(text: str, *, subject: str = "", title: str = "") -> FinancialEvent | None:
    """Read a capital-markets event from a filing. Returns None if no instrument or action can be identified."""
    head = f"{subject} {title}"
    body = _body(text)
    full = f"{head} {body}"
    ev: dict[str, str] = {}

    inst = fam = None
    for name, family, rx in INSTRUMENTS:
        m = re.search(rx, full, re.I)
        if m:
            inst, fam = name, family
            ev["instrument"] = _snippet(full, m)
            break

    # The subject line states the action most reliably ("Sub: Redemption of Commercial Paper"); fall back to the body.
    action, direction = "unknown", "unknown"
    for src in ((head, body) if subject else (body, head)):   # the filing's own "Sub:" line, else its body
        for name, rx, d in ACTIONS:
            m = re.search(rx, src, re.I)
            if m:
                action, direction = name, d
                ev["action"] = _snippet(src, m)
                break
        if action != "unknown":
            break
    if inst is None and action == "unknown":
        return None
    # A redemption *act* ("has redeemed", "redemption of", "repaid") — not the instrument's description: "redeemable
    # non-convertible debentures" and "redemption date" appear in every NCD allotment.
    redeem_act = re.compile(r"\bredeem(?:ed|s|ing)?\b|\bredemption (?:of|proceeds|amount paid)\b|maturity proceeds|\brepa(?:id|yment)\b", re.I)
    if inst in ("commercial_paper", "ncd", "bonds", "debentures", "term_loan") and action == "issuance" and \
            redeem_act.search(full) and not re.search(r"\ballot", head, re.I):
        # "issued on 14 August … has fully redeemed": the issue date is history; the event is the redemption.
        m = redeem_act.search(full)
        action, direction, ev["action"] = ("redemption" if "rede" in m.group(0).lower() or "maturity" in m.group(0).lower()
                                           else "repayment"), "outflow", _snippet(full, m)

    stage = "unknown"
    pending = re.compile(r"(?:subject to|pending|seek(?:ing)?|for (?:the )?(?:approval|consent) of|to obtain)\W+(?:\w+\W+){0,3}$|"
                         r"\b(?:to be|will be|shall be|proposed to be|would be)\s*$", re.I)
    for name, rx in STAGES:
        for src in (body, head):
            # "subject to approval of the shareholders" is a condition still to be met, not an approval obtained.
            m = next((m for m in re.finditer(rx, src, re.I) if not pending.search(src[max(0, m.start() - 40): m.start()])), None)
            if m:
                stage = name
                ev["stage"] = _snippet(src, m)
                break
        if stage != "unknown":
            break

    amount = amount_text = None
    best = None
    def amounts_in(t: str):
        f = [(m, float(m.group(1).replace(",", "")) * UNIT_TO_CRORE.get(m.group(2).lower().rstrip("."), 1.0)) for m in AMOUNT_RE.finditer(t)]
        # Amounts printed in rupees ("₹ 57,99,99,97,400") — convert to crore; ignore small per-unit prices.
        return f + [(m, float(m.group(1).replace(",", "")) / 1e7) for m in RUPEES_RE.finditer(t)
                    if float(m.group(1).replace(",", "")) >= 1e7]
    amt_src = body if amounts_in(body) else full
    found = amounts_in(amt_src)
    for m, v in found:
        # Prefer the amount stated next to the instrument or action; otherwise the largest.
        near = bool(re.search(r"commercial paper|cps?\b|debenture|ncd|bond|warrant|qip|issue|redeem|allot|aggregat|total",
                              amt_src[max(0, m.start() - 120): m.end() + 60], re.I))
        key = (near, v)
        if best is None or key > best[0]:
            best = (key, v, m)
    if best:
        _, amount, m = best
        amount_text = m.group(0).strip()
        ev["amount"] = _snippet(amt_src, m)

    unit_price = None
    cands = []
    src_text = body if UNIT_PRICE_RE.search(body) else full   # quote the filing itself before any index summary
    for mp in UNIT_PRICE_RE.finditer(src_text):
        before = src_text[max(0, mp.start() - 45): mp.start()].lower()
        if "face value" in before or "nominal value" in before:
            continue   # "face value of ₹1 each" is not the issue price
        priced = bool(re.search(r"issue price|floor price|price of|at an? (?:issue )?price|premium", before))
        cands.append((not priced, mp.start(), mp))
    if cands:
        mp = sorted(cands)[0][2]
        unit_price = float(mp.group(1).replace(",", ""))
        ev["unit_price"] = _snippet(src_text, mp)
    dates = []
    for m in DATE_RE.finditer(body):
        dates.append(" ".join(x for x in m.groups() if x))
    return FinancialEvent(instrument=inst, instrument_family=fam, action=action, capital_direction=direction, stage=stage,
                          amount=round(amount, 4) if amount is not None else None, amount_text=amount_text, unit_price=unit_price,
                          isins=list(dict.fromkeys(ISIN_RE.findall(full))), dates=list(dict.fromkeys(dates))[:4],
                          evidence=ev)


def event_identity(fe: FinancialEvent) -> str | None:
    """Two filings describe the same transaction only if instrument and action agree and the ISIN (or amount) matches.
    Different commercial-paper redemptions on different days are different events."""
    if fe.instrument is None:
        return None
    fam = "outflow" if fe.capital_direction == "outflow" else "inflow"
    if fe.isins:
        return f"fin:{fam}:{fe.instrument}:{sorted(fe.isins)[0]}"
    if fe.unit_price is not None:   # approval and allotment of the same issue share the issue price
        return f"fin:{fam}:{fe.instrument}:@{fe.unit_price:g}"
    if fe.amount is not None:
        return f"fin:{fam}:{fe.instrument}:{fe.amount:g}"
    return None


def identity_from_dict(d: dict | None) -> str | None:
    if not d:
        return None
    keep = {k: d.get(k) for k in ("instrument", "instrument_family", "action", "capital_direction", "stage", "amount",
                                  "unit_price", "isins")}
    keep["isins"] = keep["isins"] or []
    return event_identity(FinancialEvent(**keep))


def why_it_matters(fe: FinancialEvent, size_ctx: str | None, scale: str | None) -> str:
    """Direction-aware explanation: dilution and use of proceeds only apply to money coming in."""
    amt, share = (size_ctx.split(" ≈ ", 1) + [None])[:2] if size_ctx else (None, None)
    size = f" of {amt}" if amt else ""
    tail = (f" ({share}; {scale[0].lower() + scale[1:-1]})." if share and scale else f" ({share})." if share else ".")
    stage = fe.stage
    if fe.action in ("redemption", "repayment"):
        inst = INSTRUMENT_LABEL.get(fe.instrument or "", "debt")
        what = ("redeemed and paid to holders" if fe.action == "redemption" else "repaid") if stage == "completed" else \
            ("to be redeemed" if fe.action == "redemption" else "to be repaid")
        return (f"{inst[0].upper() + inst[1:]}{size} {what}{tail} Money flows out to lenders, so short-term borrowings fall; "
                "no new capital is raised and there is no dilution. Usually routine debt servicing at maturity.")
    if fe.action == "buyback":
        return f"Buyback{size}{tail} Cash goes back to shareholders and the share count falls; check the price and the cash left afterwards."
    if fe.action == "issuance":
        where = {"completed": "The raise is complete", "allotment": "Securities have been allotted",
                 "opened": "The issue has opened", "regulatory_approval": "A regulator has approved it",
                 "shareholder_approval": "Shareholders have approved it", "board_approval": "The board has approved it — nothing is raised yet",
                 "proposed": "Only proposed so far"}.get(stage, "Stage not stated")
        if fe.instrument_family == "equity":
            return (f"Equity raise{size}{tail} {where}. New shares or warrants can dilute existing holders; "
                    "check the price versus market and what the money is for.")
        if fe.instrument_family == "debt":
            return f"Borrowing{size}{tail} {where}. Adds debt rather than diluting equity; check the cost and the purpose."
        return f"Capital raise{size}{tail} {where}. Check the instrument, price and use of funds."
    return f"Capital-markets disclosure{size}{tail} The filing does not state a clear issuance or repayment; open it to check."


def scoring_mods(fe: FinancialEvent) -> list[tuple[str, int]]:
    mods: list[tuple[str, int]] = []
    if fe.stage == "completed":
        mods.append(("Filing confirms the transaction is completed", 0))
    if fe.action in ("redemption", "repayment") and fe.instrument_family == "debt":
        mods.append(("Routine debt repayment (money out, no new capital)", -35))
    if fe.action == "issuance" and fe.stage in ("board_approval", "proposed"):
        mods.append(("Approval or proposal only — nothing raised yet", -8))
    if fe.action == "issuance" and fe.stage in ("allotment", "completed") and fe.instrument_family == "equity":
        mods.append(("Equity actually issued (allotment/completion)", 6))
    return mods
